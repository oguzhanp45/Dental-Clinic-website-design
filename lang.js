/**
 * 1. Dili Değiştiren Ana Fonksiyon
 * HTML'deki butonlar burayı tetikler (onclick="changeLanguage('en')")
 */
function changeLanguage(lang) {
    // Seçilen dili hafızaya al
    localStorage.setItem('qline_lang', lang);

    // Çevirileri uygula
    applyTranslations(lang);

    // Butonların rengini güncelle
    updateButtons(lang);
}

/**
 * 2. Çevirileri Ekrana Yansıtan Fonksiyon
 */
function applyTranslations(lang) {
    // Sayfadaki data-lang etiketli her şeyi bul
    const elements = document.querySelectorAll('[data-lang]');

    elements.forEach(el => {
        const key = el.getAttribute('data-lang');

        // Eğer sözlükte bu kelimenin karşılığı varsa:
        if (translations[lang] && translations[lang][key]) {

            // KONTROL: Bu bir Input kutusu mu? (Placeholder değişmeli)
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            }
            // KONTROL: Bu bir Resim mi? (Alt yazısı değişmeli - SEO için)
            else if (el.tagName === 'IMG') {
                el.alt = translations[lang][key];
            }
            // YOKSA: Normal metindir (h1, p, span, a, label...)
            else {
                el.innerText = translations[lang][key];
            }
        }
    });
}

/**
 * 3. Butonların Görünümünü Ayarlayan Fonksiyon
 * (Aktif olan dil parlak, diğeri sönük olur)
 */
function updateButtons(lang) {
    const btnTr = document.getElementById('btn-tr');
    const btnEn = document.getElementById('btn-en');

    // Eğer butonlar bu sayfada varsa (Hata almamak için kontrol)
    if (btnTr && btnEn) {
        if (lang === 'tr') {
            btnTr.classList.add('active');
            btnEn.classList.remove('active');
        } else {
            btnEn.classList.add('active');
            btnTr.classList.remove('active');
        }
    }
}

/**
 * 4. Sayfa Yüklendiğinde Otomatik Çalışan Başlangıç Kodu
 */
document.addEventListener('DOMContentLoaded', () => {
    // Hafızaya bak, dil var mı? Yoksa 'tr' varsay.
    const savedLang = localStorage.getItem('qline_lang') || 'tr';

    // Dili yükle
    changeLanguage(savedLang);
});